const cache = new Map();

/** Inline SVG for a technology mark (decorative, aria-hidden). Unknown names return "". */
export function mark(name, className = "mark") {
  const key = `${name}|${className}`;
  if (cache.has(key)) return cache.get(key);
  const m = MARKS[name];
  if (!m) return "";
  const parts = [];
  if (m.d) parts.push(`<path d="${m.d}"/>`);
  if (m.e) parts.push(`<path fill-rule="evenodd" d="${m.e}"/>`);
  if (m.s) {
    parts.push(
      `<path d="${m.s}" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="square" stroke-linejoin="miter"/>`
    );
  }
  const svg = `<svg class="${className}" viewBox="0 0 24 24" aria-hidden="true" focusable="false" fill="currentColor" data-mark="${name}">${parts.join("")}</svg>`;
  cache.set(key, svg);
  return svg;
}

/** Brand tint for a mark (a hex colour or a token reference), or the gold token. */
export function tint(name) {
  return MARKS[name]?.tint ?? "var(--gold)";
}
